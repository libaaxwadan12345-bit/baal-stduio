-- BS Entertainment: public guest comments + reactions
-- Run this whole script in Supabase > SQL Editor > New query.

create table if not exists public.episode_comments (
  id bigint generated by default as identity primary key,
  episode_key text not null check (char_length(episode_key) between 3 and 180),
  guest_name text not null check (char_length(guest_name) between 2 and 30),
  body text not null check (char_length(body) between 2 and 500),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

create index if not exists episode_comments_public_idx
  on public.episode_comments (episode_key, status, created_at desc);

create table if not exists public.episode_reactions (
  id bigint generated by default as identity primary key,
  episode_key text not null check (char_length(episode_key) between 3 and 180),
  visitor_id text not null check (char_length(visitor_id) between 8 and 100),
  emoji text not null check (emoji in ('❤️','🔥','😍','😂','😢')),
  created_at timestamptz not null default now(),
  unique (episode_key, visitor_id)
);

alter table public.episode_comments enable row level security;
alter table public.episode_reactions enable row level security;

-- Anyone can read only approved comments.
drop policy if exists "Anyone reads approved comments" on public.episode_comments;
create policy "Anyone reads approved comments"
  on public.episode_comments for select to anon, authenticated
  using (status = 'approved');

-- Guests may submit comments, but every new comment must be pending.
drop policy if exists "Guests submit pending comments" on public.episode_comments;
create policy "Guests submit pending comments"
  on public.episode_comments for insert to anon, authenticated
  with check (status = 'pending');

-- Public visitors can see reaction rows to calculate emoji totals.
drop policy if exists "Anyone reads reactions" on public.episode_reactions;
create policy "Anyone reads reactions"
  on public.episode_reactions for select to anon, authenticated
  using (true);

-- Guests can add/update only their browser-generated visitor id reaction.
drop policy if exists "Guests add reactions" on public.episode_reactions;
create policy "Guests add reactions"
  on public.episode_reactions for insert to anon, authenticated
  with check (true);

drop policy if exists "Guests update reactions" on public.episode_reactions;
create policy "Guests update reactions"
  on public.episode_reactions for update to anon, authenticated
  using (true) with check (true);

-- No public update/delete policies are created for comments.
-- Moderate comments in Supabase Table Editor as the project owner:
-- pending -> approved (visible on the site), or rejected (not visible).


-- Public audition / voice-acting applications. Visitors can submit without an account.
create table if not exists public.audition_applications (
  id bigint generated by default as identity primary key,
  applicant_name text not null check (char_length(applicant_name) between 2 and 80),
  contact text not null check (char_length(contact) between 3 and 120),
  desired_role text not null check (char_length(desired_role) between 2 and 80),
  experience text not null default '' check (char_length(experience) <= 200),
  message text not null default '' check (char_length(message) <= 1000),
  status text not null default 'new' check (status in ('new','reviewing','accepted','declined')),
  created_at timestamptz not null default now()
);

alter table public.audition_applications enable row level security;
drop policy if exists "Anyone can submit audition application" on public.audition_applications;
create policy "Anyone can submit audition application"
  on public.audition_applications for insert to anon, authenticated
  with check (status = 'new');
-- No public SELECT, UPDATE, or DELETE policies: applicant details stay private.
-- Review applications only in Supabase Table Editor while signed in as project owner.
